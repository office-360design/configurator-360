export function arLocale(value) { return ['en-US', 'ro-RO', 'de-DE'].includes(value) ? value : 'en-US'; }
export function arT(product, locale, key, variables = {}) {
  const copy = AR_COPY[product] || AR_COPY.hall;
  let text = copy[arLocale(locale)][key] || copy['en-US'][key] || copy['en-US'].generic;
  for (const [name, value] of Object.entries(variables)) text = text.replaceAll(`{${name}}`, String(value));
  return text;
}
