const SHARED_LOCALE_ALIASES = Object.freeze(Object.fromEntries(
  Object.keys(SHARED_MESSAGES).flatMap((code) => [[code.toLowerCase(), code], [code.split('-')[0].toLowerCase(), code]]),
));

export function normalizeConfiguratorLocale(locale) {
  const value = String(locale ?? '').trim().replace('_', '-').toLowerCase();
  return SHARED_LOCALE_ALIASES[value] ?? 'en-US';
}

function interpolate(message, variables = {}) {
  return String(message).replace(/\{([A-Za-z0-9_]+)\}/g, (_, key) => (
    Object.prototype.hasOwnProperty.call(variables, key) ? String(variables[key]) : `{${key}}`
  ));
}

export function sharedT(locale, key, variables = {}) {
  const resolved = normalizeConfiguratorLocale(locale);
  const message = SHARED_MESSAGES[resolved]?.[key] ?? SHARED_MESSAGES['en-US'][key] ?? key;
  return interpolate(message, variables);
}

export function getSharedMessages(locale) {
  return SHARED_MESSAGES[normalizeConfiguratorLocale(locale)] ?? SHARED_MESSAGES['en-US'];
}
