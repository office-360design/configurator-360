const { clickTool } = require('./editor-tools.cjs');
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.ROOF_TEST_BROWSER,
    args: ['--no-sandbox', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/test-three/**', route => route.fulfill({
    path: require('node:path').join(process.env.ROOF_TEST_THREE, route.request().url().split('/test-three/')[1]), contentType: 'text/javascript',
  }));
  await page.route('**/i18n-fixture', route => route.fulfill({ contentType: 'text/html', body:
    '<script type="importmap">{"imports":{"three":"/test-three/build/three.module.js"}}</script><link rel="stylesheet" href="/roof-configurator/layout-editor.css"><link rel="stylesheet" href="/roof-configurator/sheet-planner.css"><style>body{font-family:Arial}</style>' }));
  await page.goto('http://127.0.0.1:8080/i18n-fixture');
  await page.evaluate(async () => {
    const { RoofLayoutEditor } = await import('/roof-configurator/js/layoutEditor.js');
    const { SheetPlannerUI } = await import('/roof-configurator/js/sheetPlannerUI.js');
    const { footprintLayout } = await import('/roof-configurator/js/roofLayout.js?v=layout-21');
    const layout = footprintLayout([{x:0,z:0},{x:8,z:0},{x:8,z:6},{x:0,z:6}]);
    layout.vertices.forEach(p => { p.h = p.z * .5; });
    window.state = { locale: 'ro-RO', roofType: 'layout', roofLayout: layout };
    window.editor = new RoofLayoutEditor(state, () => {});
    window.planner = new SheetPlannerUI(state);
    window.changeLocale = locale => { state.locale = locale; window.dispatchEvent(new CustomEvent('roof-locale-applied', { detail: { locale } })); };
    editor.open();
  });
  const alert = page.locator('.layout-feedback');
  await clickTool(page, 'window');
  assert.ok(await alert.isVisible());
  assert.equal(await alert.getAttribute('data-severity'), 'warning');
  assert.match(await alert.innerText(), /Completează acest pas/);
  await page.locator('[data-window=x]').fill('3');
  await page.locator('[data-window=z]').fill('3');
  assert.ok(await alert.isHidden());
  const original = await page.evaluate(() => JSON.stringify(editor.layout));
  await page.locator('[data-window=width]').fill('5');
  assert.equal(await alert.getAttribute('data-severity'), 'error');
  assert.equal(await page.locator('.layout-issue-marker').count(), 1);
  assert.equal(await page.locator('[data-window=status]').getAttribute('data-severity'), 'error');
  assert.ok(await page.locator('[data-window=save]').isDisabled());
  assert.equal(await page.evaluate(() => JSON.stringify(editor.layout)), original);
  await page.locator('[data-action=zoomIn]').click();
  assert.ok(await alert.isVisible(), 'Zoom must not dismiss an unresolved error');
  assert.equal(await page.locator('.layout-issue-marker').count(), 1);
  await page.evaluate(() => changeLocale('de-DE'));
  assert.match(await alert.innerText(), /Vorschau muss korrigiert werden/);
  await page.setViewportSize({ width: 390, height: 844 });
  const box = await alert.boundingBox();
  assert.ok(box.y >= 0 && box.y + box.height <= 844, 'Alert remains within mobile viewport');
  assert.equal(await page.locator('.roof-layout-dialog').evaluate(el => el.scrollWidth > el.clientWidth + 1), false);
  await page.screenshot({ path: '/tmp/roof-feedback-mobile.png' });
  await page.locator('.layout-feedback-dismiss').click();
  assert.ok(await alert.isHidden());
  assert.equal(await page.locator('.layout-issue-marker').count(), 0);
  assert.equal(await page.locator('[data-window=status]').getAttribute('data-severity'), 'error', 'Dismiss does not mark invalid inputs valid');
  await page.locator('[data-window=width]').fill('1');
  assert.equal(await page.locator('[data-window=status]').getAttribute('data-severity'), 'success');
  assert.ok(await page.locator('[data-window=save]').isEnabled());
  await page.locator('[data-window=cancel]').click();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.evaluate(() => { changeLocale('en-US'); editor.selected = 0; editor.render(); });
  await page.locator('#layoutX').fill('200');
  await page.locator('[data-action=point]').click();
  assert.match(await alert.innerText(), /Change not applied/);
  assert.equal(await page.evaluate(() => JSON.stringify(editor.layout)), original);
  assert.equal(await page.locator('.layout-issue-marker').count(), 1);
  await page.screenshot({ path: '/tmp/roof-feedback-desktop.png' });
  await page.locator('#layoutX').fill('0');
  await page.locator('[data-action=point]').click();
  assert.ok(await alert.isHidden());
  await clickTool(page, 'dormer');
  await page.locator('#dormerWidth').fill('9');
  assert.match(await alert.innerText(), /width of 0.5–8 m/);
  assert.equal(await page.locator('#dormerResult').getAttribute('data-severity'), 'error');
  await page.locator('[data-action=cancelDormer]').click();
  assert.ok(await alert.isHidden());
  await page.evaluate(() => { editor.selected = 0; editor.render(); });
  await page.locator('[data-action=meet]').click();
  assert.equal(await alert.getAttribute('data-severity'), 'warning');
  assert.match(await alert.innerText(), /Choose the target roof slope/);
  await page.locator('[data-action=cancelMeet]').click();
  assert.ok(await alert.isHidden());
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('PASS editor feedback: invalid geometry, previews, markers, correction, dismissal, languages and mobile visibility');
})().catch(error => { console.error(error); process.exit(1); });
