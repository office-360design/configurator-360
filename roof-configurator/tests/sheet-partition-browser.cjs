const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.ROOF_TEST_BROWSER, args:['--no-sandbox'] });
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.route('**/sheet-fixture', route => route.fulfill({contentType:'text/html',body:'<link rel="stylesheet" href="/roof-configurator/sheet-planner.css"><body style="font-family:Arial"></body>'}));
  await page.goto('http://127.0.0.1:8080/sheet-fixture');
  await page.evaluate(async () => {
    const {SheetPlannerUI} = await import('/roof-configurator/js/sheetPlannerUI.js');
    window.state = {roofType:'gable',length:3,depth:21.21762239271875,overhang:0,pitch:30,locale:'en-US'};
    window.planner = new SheetPlannerUI(state);
    planner.open();
  });
  const slope = page.locator('[data-plan-slope="0"]');
  const modules = () => page.evaluate(() => planner.plan.slopes[0].pieces.filter(p => p.column===1).map(p => p.modules));
  assert.deepEqual(await modules(),[22,13]);
  // Actual diagram click selects another column and its original section.
  await slope.locator('[data-piece-base="A-2.1"]').click();
  assert.equal(await slope.locator('[data-partition-column]').inputValue(),'2');
  await slope.locator('[data-partition-column]').selectOption('1');
  await slope.locator('[data-partition-value]').fill('11 + 11');
  await slope.locator('[data-partition-action=apply]').click();
  assert.deepEqual(await modules(),[11,11,13]);
  assert.equal(await slope.locator('.selected-section').count(),2);
  assert.match(await slope.locator('.sheet-partition').innerText(),/200 mm total end allowance/);
  const before = await page.evaluate(() => JSON.stringify(planner.plan));
  await slope.locator('[data-partition-value]').fill('7 + 7 + 7');
  await slope.locator('[data-partition-action=apply]').click();
  assert.ok(await slope.locator('[data-partition-error]').isVisible());
  assert.equal(await page.evaluate(() => JSON.stringify(planner.plan)),before);
  await slope.locator('[data-partition-value]').fill('7 + 7 + 8');
  await slope.locator('[data-partition-scope]').selectOption('surface');
  await slope.locator('[data-partition-action=apply]').click();
  assert.deepEqual(await modules(),[7,7,8,13]);
  assert.equal(await page.evaluate(() => planner.plan.slopes[0].pieces.length),12);
  assert.equal(await page.evaluate(() => planner.plan.slopes[1].pieces.length),6);
  await slope.locator('[data-partition-scope]').selectOption('global');
  await slope.locator('[data-partition-action=apply]').click();
  assert.equal(await page.evaluate(() => planner.plan.slopes[1].pieces.length),12);
  // Restoring a surface is one undoable change and leaves other surfaces intact.
  await slope.locator('[data-partition-action=restoreSurface]').click();
  assert.deepEqual(await modules(),[22,13]);
  assert.equal(await page.evaluate(() => planner.plan.slopes[1].pieces.length),12);
  await page.locator('[data-sheet=undo]').click();
  assert.deepEqual(await modules(),[7,7,8,13]);
  await page.locator('[data-sheet=redo]').click();
  assert.deepEqual(await modules(),[22,13]);
  await page.locator('[data-sheet=undo]').click();
  await page.locator('[data-sheet=restoreAll]').click();
  assert.equal(await page.evaluate(() => planner.plan.totals.count),12);
  assert.ok(await page.locator('[data-sheet=restoreAll]').isDisabled());
  await page.locator('[data-sheet=undo]').click();
  assert.equal(await page.evaluate(() => planner.plan.totals.count),24);
  const downloadEvent = page.waitForEvent('download');
  await page.locator('[data-sheet=csv]').click();
  const download = await downloadEvent;
  const csv = require('fs').readFileSync(await download.path(),'utf8');
  assert.match(csv,/A-1.1,1,7,2550/);
  await page.locator('[data-sheet=close]').last().click();
  await page.evaluate(() => planner.open());
  assert.deepEqual(await modules(),[7,7,8,13]);
  assert.ok(await page.locator('[data-sheet=redo]').isEnabled());
  await page.locator('[data-sheet=redo]').click();
  assert.equal(await page.evaluate(() => planner.plan.totals.count),12);
  await page.locator('[data-sheet=undo]').click();
  await page.locator('button[type=submit]').click();
  assert.deepEqual(await modules(),[7,7,8,13]);
  await page.evaluate(() => {state.locale='ro-RO';window.dispatchEvent(new Event('roof-locale-applied'));});
  assert.match(await slope.locator('legend').innerText(),/Împărțirea/);
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(() => {state.locale='de-DE';window.dispatchEvent(new Event('roof-locale-applied'));});
  assert.equal(await page.locator('.sheet-planner').evaluate(el => el.scrollWidth > el.clientWidth+1),false);
  await slope.locator('[data-partition-value]').scrollIntoViewIfNeeded();
  await page.screenshot({path:'/tmp/sheet-partition-mobile.png'});
  await page.setViewportSize({width:1440,height:1000});
  await page.evaluate(() => {state.locale='en-US';window.dispatchEvent(new Event('roof-locale-applied'));});
  await slope.locator('[data-partition-scope]').selectOption('global');
  await slope.locator('[data-partition-action=reset]').click();
  assert.deepEqual(await modules(),[22,13]);
  assert.equal(await page.evaluate(() => planner.plan.totals.count),12);
  await slope.locator('[data-partition-value]').fill('11 + 11');
  await slope.locator('[data-partition-action=apply]').click();
  assert.ok(await page.locator('[data-sheet=redo]').isDisabled());
  await slope.locator('.sheet-partition').scrollIntoViewIfNeeded();
  await page.screenshot({path:'/tmp/sheet-partition-desktop.png'});
  await page.locator('[name=offset]').fill('100');
  assert.ok(await slope.locator('[data-partition-action=apply]').isDisabled());
  assert.ok(await page.locator('[data-sheet=undo]').isDisabled());
  await page.locator('button[type=submit]').click();
  assert.match(await page.locator('.sheet-report-summary').innerText(),/Custom partitions were reset/);
  assert.ok(await page.locator('[data-sheet=undo]').isDisabled());
  assert.ok(await page.locator('[data-sheet=redo]').isDisabled());
  assert.deepEqual(await page.evaluate(() => state.sheetPlanOptions.partitions || {}),{});
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('PASS partitions: selection, splits, validation, bulk scopes, reset, persistence, CSV, stale settings, RO/DE and mobile');
})().catch(error => {console.error(error);process.exit(1);});
