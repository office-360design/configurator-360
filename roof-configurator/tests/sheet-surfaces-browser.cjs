const {chromium} = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({executablePath:process.env.ROOF_TEST_BROWSER,args:['--no-sandbox']});
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/surface-fixture',route=>route.fulfill({contentType:'text/html',body:'<meta name="viewport" content="width=device-width, initial-scale=1"><link rel="stylesheet" href="/roof-configurator/sheet-planner.css">'}));
  await page.goto('http://127.0.0.1:8080/surface-fixture');
  await page.evaluate(async()=>{
    const {SheetPlannerUI}=await import('/roof-configurator/js/sheetPlannerUI.js');
    window.state={roofType:'gable',length:10,depth:7,overhang:.3,pitch:30,locale:'en-US'};
    window.roofBefore=JSON.stringify(state);
    window.planner=new SheetPlannerUI(state);
    planner.open();
  });
  await page.locator('.sheet-edit-surfaces').click();
  const editor=page.locator('.sheet-surface-editor');
  await editor.locator('[data-action=draw]').click();
  const clickAt=async(x,y)=>{
    const p=await page.evaluate(({x,y})=>{
      const e=planner.surfaceEditor;
      return new DOMPoint(65+(x-e.minX)*e.scale,455-(y-e.minY)*e.scale).matrixTransform(e.svg.getScreenCTM()).toJSON();
    },{x,y});
    await page.mouse.click(p.x,p.y);
  };
  await clickAt(10,0); await clickAt(8,5); await clickAt(2,5);
  await editor.locator('[data-action=finish]').click();
  assert.deepEqual(await page.evaluate(()=>planner.surfaceEditor.surfaces[0]),[{x:0,y:0},{x:10,y:0},{x:8,y:5},{x:2,y:5}]);
  await editor.locator('[data-action=duplicate]').click();
  assert.equal(await page.evaluate(()=>planner.surfaceEditor.surfaces.length),2);
  await editor.locator('.surface-width').fill('6'); await editor.locator('.surface-height').fill('4');
  await editor.locator('[data-action=triangle]').click();
  assert.equal(await page.evaluate(()=>planner.surfaceEditor.surfaces.length),3);
  await editor.locator('[data-action=undo]').click();
  assert.equal(await page.evaluate(()=>planner.surfaceEditor.surfaces.length),2);
  await editor.locator('[data-action=redo]').click();
  // Invalid coordinate edits leave the valid surface intact and show a visible box.
  const before=await page.evaluate(()=>JSON.stringify(planner.surfaceEditor.surfaces));
  await editor.locator('[data-point="0"][data-axis=x]').fill('150');
  await editor.locator('[data-point="0"][data-axis=x]').press('Tab');
  assert.equal(await page.evaluate(()=>JSON.stringify(planner.surfaceEditor.surfaces)),before);
  assert.equal(await editor.locator('.surface-error').isVisible(),true);
  await editor.locator('[data-action=apply]').click();
  assert.equal(await page.locator('.sheet-source-select').inputValue(),'surfaces');
  assert.equal(await page.locator('.sheet-slope[data-plan-slope]').count(),3);
  assert.equal(await page.evaluate(()=>planner.plan.totals.netArea),92);
  assert.equal(await page.evaluate(()=>state.roofType),'gable');
  assert.equal(await page.evaluate(()=>state.length),10);
  assert.equal(await page.evaluate(()=>state.roofLayout),undefined);
  assert.match(await page.locator('.sheet-report-summary').innerText(),/Independent 2D surfaces/);
  const totals=await page.evaluate(()=>JSON.stringify(planner.plan.totals));
  await page.evaluate(()=>{planner.dialog.close();planner.open();});
  assert.equal(await page.evaluate(()=>JSON.stringify(planner.plan.totals)),totals);
  await page.locator('.sheet-source-select').selectOption('roof');
  await page.locator('.sheet-primary[form]').click();
  assert.equal(await page.evaluate(()=>!!planner.plan.drawnSurfaces),false);
  await page.locator('.sheet-source-select').selectOption('surfaces');
  await page.locator('.sheet-primary[form]').click();
  assert.equal(await page.evaluate(()=>JSON.stringify(planner.plan.totals)),totals);
  await page.evaluate(()=>{state.locale='ro-RO';window.dispatchEvent(new Event('roof-locale-applied'));});
  await page.locator('.sheet-edit-surfaces').click();
  assert.equal(await editor.locator('h2').innerText(),'Desenează suprafețe 2D');
  await editor.locator('[data-action=delete]').click();
  await editor.locator('[data-action=cancel]').last().click();
  assert.equal(await page.evaluate(()=>state.sheetSurfaces.length),3);
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>{state.locale='de-DE';window.dispatchEvent(new Event('roof-locale-applied'));});
  await page.locator('.sheet-edit-surfaces').click();
  assert.equal(await editor.locator('h2').innerText(),'2D-Flächen zeichnen');
  assert.ok(await editor.evaluate(el=>el.scrollWidth<=el.clientWidth+1));
  await page.screenshot({path:'/tmp/roof-surfaces-mobile.png'});
  await editor.locator('[data-action=apply]').click();
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('PASS 2D drawing, duplicate, presets, undo/redo, validation, totals, source switching, reopen, cancel, RO/DE and mobile');
})().catch(e=>{console.error(e);process.exit(1);});
