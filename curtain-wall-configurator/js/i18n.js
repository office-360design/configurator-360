export const MESSAGES = { 'en-US': en, 'ro-RO': ro, 'de-DE': de, 'es-ES': es, 'fr-FR': fr, 'it-IT': it };

export function resolveLocale(locale) {
  const value = String(locale || '');
  if (/^ro/i.test(value)) return 'ro-RO';
  if (/^de/i.test(value)) return 'de-DE';
  if (/^es/i.test(value)) return 'es-ES';
  if (/^fr/i.test(value)) return 'fr-FR';
  if (/^it/i.test(value)) return 'it-IT';
  if (/^en/i.test(value)) return 'en-US';
  return 'ro-RO';
}

export function translator(locale) {
  const table = MESSAGES[resolveLocale(locale)];
  return (key, vars = {}) => String(table[key] ?? ro[key] ?? key).replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? `{${name}}`));
}

export function applyTranslations(root, t) {
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
}
