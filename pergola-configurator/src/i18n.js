export const PERGOLA_MESSAGES = Object.freeze({
  'en-US': Object.freeze(EN),
  'ro-RO': Object.freeze(RO),
  'de-DE': Object.freeze(DE),
});

function interpolate(message, variables = {}) {
  return String(message).replace(/\{([A-Za-z0-9_]+)\}/g, (_, key) => (
    Object.prototype.hasOwnProperty.call(variables, key) ? String(variables[key]) : `{${key}}`
  ));
}

export function pergolaT(locale, key, variables = {}) {
  const resolved = normalizeConfiguratorLocale(locale);
  const message = PERGOLA_MESSAGES[resolved]?.[key] ?? EN[key] ?? key;
  return interpolate(message, variables);
}

export function pergolaPlural(locale, key, count, variables = {}) {
  return pergolaT(locale, `${key}.${Number(count) === 1 ? 'one' : 'other'}`, { count, ...variables });
}

export function localizeCatalogOptions(locale, group, options) {
  return options.map((option) => {
    const prefix = `catalog.${group}.${option.value}`;
    const labelKey = `${prefix}.label`;
    const descriptionKey = `${prefix}.description`;
    const badgeKey = `${prefix}.badge`;
    const localized = { ...option, label: pergolaT(locale, labelKey) };
    if (option.description) localized.description = pergolaT(locale, descriptionKey);
    if (option.badge) localized.badge = pergolaT(locale, badgeKey);
    return localized;
  });
}

export function localizeStep(locale, step) {
  return { ...step, label: pergolaT(locale, `steps.${step.id}`) };
}

export function pergolaValueLabel(locale, group, value) {
  return pergolaT(locale, `value.${group}.${value}`);
}

export function localizePoleLabel(locale, label) {
  const match = /^Pole\s+(\d+)-(\d+)$/i.exec(String(label ?? ''));
  if (!match) return String(label ?? '');
  return pergolaT(locale, 'grid.pole', { row: match[1], column: match[2] });
}

export function localizeRoofRectangleLabel(locale, label) {
  const match = /^Roof rectangle\s+(\d+)-(\d+)$/i.exec(String(label ?? ''));
  if (!match) return String(label ?? '');
  return pergolaT(locale, 'grid.roofRectangle', { row: match[1], column: match[2] });
}

const RUNTIME_MESSAGE_KEYS = Object.freeze({
  'That grid segment is not available for a side closing.': 'runtime.segmentUnavailable',
  'Remove the components from the two connected pole faces before closing this segment.': 'runtime.segmentMountedItems',
  'That component is not available on this pole face.': 'runtime.componentUnavailable',
  'That weather sensor cannot be placed on this pole.': 'runtime.sensorUnavailable',
});

export function translatePergolaRuntimeMessage(locale, message) {
  const key = RUNTIME_MESSAGE_KEYS[String(message ?? '')];
  return key ? pergolaT(locale, key) : String(message ?? '');
}
