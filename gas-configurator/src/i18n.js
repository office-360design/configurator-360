export const GAS_DICTIONARIES = Object.freeze({
  'en-US': EN,
  'ro-RO': RO,
  'de-DE': DE,
  'es-ES': ES,
  'fr-FR': FR,
  'it-IT': IT,
});

export function gasT(locale, key, variables = {}) {
  const dictionary = GAS_DICTIONARIES[locale] || EN;
  let value = dictionary[key] ?? EN[key] ?? key;
  Object.entries(variables).forEach(([name, replacement]) => {
    value = value.replaceAll(`{${name}}`, String(replacement));
  });
  return value;
}

export function applyGasTranslations(root, locale) {
  if (!root) return;
  root.querySelectorAll('[data-gas-i18n]').forEach((element) => {
    element.textContent = gasT(locale, element.dataset.gasI18n);
  });
  root.querySelectorAll('[data-gas-i18n-title]').forEach((element) => {
    element.title = gasT(locale, element.dataset.gasI18nTitle);
  });
  root.querySelectorAll('[data-gas-i18n-aria-label]').forEach((element) => {
    element.setAttribute('aria-label', gasT(locale, element.dataset.gasI18nAriaLabel));
  });
}
