export function translator(locale = 'en-US') {
  const values = locale.startsWith('ro') ? ro : locale.startsWith('de') ? de : en;
  const dict = Object.fromEntries(keys.map((key, i) => [key, values[i]]));
  Object.assign(
    dict,
    mapCopy[locale.split('-')[0]] || mapCopy.en,
    areaCopy[locale.split('-')[0]] || areaCopy.en,
    houseCopy[locale.split('-')[0]] || houseCopy.en,
  );
  return (key) => dict[key] || key;
}
