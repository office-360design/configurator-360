export function solarFormatAzimuth(azimuth, locale = null) {
  const normalized = ((Number(azimuth) || 0) % 360 + 360) % 360;
  const directions = ['N', 'NE', 'E', 'SE', 'S', 'SW', 'W', 'NW'];
  const index = Math.round(normalized / 45) % 8;
  return `${Math.round(normalized)}° ${solarT(locale, `azimuth.${directions[index]}`)}`;
}

