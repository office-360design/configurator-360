function buildReverseMap(source) {
  const reverse = new Map();
  Object.entries(source).forEach(([english, values]) => {
    reverse.set(english, english);
    values.forEach((value) => reverse.set(value, english));
  });
  return reverse;
}

const STATIC_REVERSE = buildReverseMap(STATIC_TRANSLATIONS);
const ATTR_REVERSE = buildReverseMap(ATTR_TRANSLATIONS);

function targetStaticText(english, locale) {
  const entry = STATIC_TRANSLATIONS[english];
  if (!entry || locale === 'en-US') return english;
  return locale === 'ro-RO' ? entry[0] : entry[1];
}

function targetAttrText(english, locale) {
  const entry = ATTR_TRANSLATIONS[english];
  if (!entry || locale === 'en-US') return english;
  return locale === 'ro-RO' ? entry[0] : entry[1];
}

export function applySolarTranslations(locale = null) {
  if (typeof document === 'undefined') return resolveSolarLocale(locale);
  const resolved = resolveSolarLocale(locale);
  document.documentElement.lang = resolved === 'ro-RO' ? 'ro' : resolved === 'de-DE' ? 'de' : 'en';

  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach((node) => {
    if (['SCRIPT', 'STYLE', 'TEMPLATE'].includes(node.parentElement?.tagName)) return;
    const raw = node.nodeValue || '';
    const trimmed = raw.trim();
    if (!trimmed) return;
    const english = STATIC_REVERSE.get(trimmed);
    if (!english) return;
    const translated = targetStaticText(english, resolved);
    node.nodeValue = `${raw.match(/^\s*/)?.[0] || ''}${translated}${raw.match(/\s*$/)?.[0] || ''}`;
  });

  document.querySelectorAll('[aria-label], [title], [placeholder], [alt]').forEach((node) => {
    ['aria-label', 'title', 'placeholder', 'alt'].forEach((attribute) => {
      const current = node.getAttribute(attribute);
      if (!current) return;
      const english = ATTR_REVERSE.get(current);
      if (english) node.setAttribute(attribute, targetAttrText(english, resolved));
    });
  });

  const titleEnglish = STATIC_REVERSE.get(document.title);
  if (titleEnglish) document.title = targetStaticText(titleEnglish, resolved);
  window.dispatchEvent(new CustomEvent('solar-locale-applied', { detail: { locale: resolved } }));
  return resolved;
}
