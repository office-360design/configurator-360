function interpolate(message, variables = {}) {
  return String(message).replace(/\{([A-Za-z0-9_]+)\}/g, (_, key) => (
    Object.prototype.hasOwnProperty.call(variables, key) ? String(variables[key]) : `{${key}}`
  ));
}

export function resolveSolarLocale(locale = null) {
  if (locale) return normalizeConfiguratorLocale(locale);
  if (typeof window === 'undefined') return 'en-US';
  return normalizeConfiguratorLocale(window.SOLAR_CONFIGURATOR_SHARED_SHELL?.state?.locale || getLocaleForHostname(window.location.hostname));
}

export function getSolarMessages(locale = null) {
  return MESSAGES[resolveSolarLocale(locale)] ?? MESSAGES['en-US'];
}

