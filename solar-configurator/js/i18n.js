function buildReverseMap(source) {
  // English keys always win; among translations the first entry wins, so a collision such as
  // es/fr/it "O" (West) vs. de "O" (East) cannot silently remap an English source string.
  const reverse = new Map();
  Object.values(source).forEach((values) => {
    values.forEach((value) => { if (!reverse.has(value)) reverse.set(value, null); });
  });
  Object.entries(source).forEach(([english, values]) => {
    values.forEach((value) => { if (reverse.get(value) === null) reverse.set(value, english); });
  });
  Object.keys(source).forEach((english) => reverse.set(english, english));
  return reverse;
}

const STATIC_REVERSE = buildReverseMap(STATIC_TRANSLATIONS);
const ATTR_REVERSE = buildReverseMap(ATTR_TRANSLATIONS);
const LOCALE_COLUMN = new Map(SOLAR_TRANSLATION_COLUMNS.map((locale, index) => [locale, index]));
// Remembers the English source of each translated text node / attribute, so repeated language switches
// never depend on reverse-mapping an ambiguous translated value.
const TEXT_SOURCES = new WeakMap();
const ATTR_SOURCES = new WeakMap();
let titleSource = null;

function translatedEntry(table, english, locale) {
  const entry = table[english];
  const column = LOCALE_COLUMN.get(locale);
  if (!entry || column === undefined) return english;
  return entry[column] || english;
}

function targetStaticText(english, locale) {
  return translatedEntry(STATIC_TRANSLATIONS, english, locale);
}

function targetAttrText(english, locale) {
  return translatedEntry(ATTR_TRANSLATIONS, english, locale);
}

function resolveSource(record, current, reverse) {
  if (record && record.applied === current) return record.english;
  return reverse.get(current) || null;
}

export function applySolarTranslations(locale = null) {
  if (typeof document === 'undefined') return resolveSolarLocale(locale);
  const resolved = resolveSolarLocale(locale);
  document.documentElement.lang = resolved.slice(0, 2);

  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach((node) => {
    if (['SCRIPT', 'STYLE', 'TEMPLATE'].includes(node.parentElement?.tagName)) return;
    const raw = node.nodeValue || '';
    const trimmed = raw.trim();
    if (!trimmed) return;
    const english = resolveSource(TEXT_SOURCES.get(node), trimmed, STATIC_REVERSE);
    if (!english) return;
    const translated = targetStaticText(english, resolved);
    TEXT_SOURCES.set(node, { english, applied: translated });
    node.nodeValue = `${raw.match(/^\s*/)?.[0] || ''}${translated}${raw.match(/\s*$/)?.[0] || ''}`;
  });

  document.querySelectorAll('[aria-label], [title], [placeholder], [alt]').forEach((node) => {
    ['aria-label', 'title', 'placeholder', 'alt'].forEach((attribute) => {
      const current = node.getAttribute(attribute);
      if (!current) return;
      let records = ATTR_SOURCES.get(node);
      const english = resolveSource(records?.[attribute], current, ATTR_REVERSE);
      if (!english) return;
      const translated = targetAttrText(english, resolved);
      if (!records) { records = {}; ATTR_SOURCES.set(node, records); }
      records[attribute] = { english, applied: translated };
      node.setAttribute(attribute, translated);
    });
  });

  const titleEnglish = resolveSource(titleSource, document.title, STATIC_REVERSE);
  if (titleEnglish) {
    document.title = targetStaticText(titleEnglish, resolved);
    titleSource = { english: titleEnglish, applied: document.title };
  }
  window.dispatchEvent(new CustomEvent('solar-locale-applied', { detail: { locale: resolved } }));
  return resolved;
}

