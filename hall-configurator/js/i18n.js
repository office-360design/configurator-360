function interpolate(message, variables = {}) {
  return String(message).replace(/\{([A-Za-z0-9_]+)\}/g, (_, key) => (
    Object.prototype.hasOwnProperty.call(variables, key) ? String(variables[key]) : `{${key}}`
  ));
}

export function hallT(locale, key, variables = {}) {
  const resolved = normalizeConfiguratorLocale(locale);
  const message = MESSAGES[resolved]?.[key] ?? MESSAGES['en-US'][key] ?? key;
  return interpolate(message, variables);
}

export function resolveHallLocale() {
  return normalizeConfiguratorLocale(
    window.HALL_CONFIGURATOR_SHARED_SHELL?.state?.locale ?? getLocaleForHostname(window.location.hostname),
  );
}

export function hallOpeningLabel(type, locale = resolveHallLocale()) {
  return hallT(locale, `opening.${type}`);
}

export function hallWallLabel(side, { short = false, locale = resolveHallLocale() } = {}) {
  return hallT(locale, `wall.${side}${short ? '' : 'Wall'}`);
}

