  const map = {
    structurePreset: { light: 'structure.light', standard: 'structure.standard', heavy: 'structure.heavy' },
    claddingProfile: { trapezoidal: 'cladding.trapezoidal', sandwich: 'cladding.sandwich', 'standing-seam': 'cladding.standingSeam' },
    climateSystem: { none: 'climate.none', comfort: 'climate.comfort', chilled: 'climate.chilled', frozen: 'climate.frozen' },
    inspectionMode: { all: 'inspection.all', primary: 'inspection.primary', secondary: 'inspection.secondary', connections: 'inspection.connections', foundations: 'inspection.foundations', envelope: 'inspection.envelope', services: 'inspection.services' },
    rackDensity: { light: 'rack.light', standard: 'rack.standard', dense: 'rack.dense' },
    serviceVisibility: { all: 'service.all', lighting: 'service.lighting', fire: 'service.fire', climate: 'service.climate', drainage: 'service.drainage', none: 'service.none' },
  };
  const key = map[group]?.[value];
  return key ? hallT(locale, key) : String(value ?? '');
