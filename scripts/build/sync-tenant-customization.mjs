import { readFile, writeFile } from 'node:fs/promises';
const source = new URL('../../firebase-share-backend/functions/tenant-customization-schema.mjs', import.meta.url);
const target = new URL('../../shared-ui/src/tenantCustomization.js', import.meta.url);
const content = '// Generated by scripts/build/sync-tenant-customization.mjs. Do not edit.\n' + await readFile(source, 'utf8');
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== content) throw new Error('Tenant customization browser contract is out of sync.');
} else await writeFile(target, content);
